func indexedImage(depth byte) *testImage {
	img := syntheticImage()
	in := img.data[5*testBlockSize+256 : 5*testBlockSize+512]
	put32(in, 32, inodeFlagExtents|inodeFlagIndex)
	count := uint16(2)
	if depth > 0 {
		count = 3
	}
	put32(in, 4, uint32(count)*testBlockSize)
	put16(in, 56, count)
	root := img.data[10*testBlockSize : 11*testBlockSize]
	clear(root)
	writeDirent(root, 0, 2, 12, ".", 2)
	writeDirent(root, 12, 2, testBlockSize-12, "..", 2)
	root[29] = 8
	root[30] = depth
	put16(root, 32, (testBlockSize-32)/8)
	put16(root, 34, 1)
	put32(root, 36, 1)
	leaf := img.data[11*testBlockSize : 12*testBlockSize]
	clear(leaf)
	if depth > 0 {
		put16(leaf, 4, testBlockSize)
		put16(leaf, 8, (testBlockSize-8)/8)
		put16(leaf, 10, 1)
		put32(leaf, 12, 2)
		leaf = img.data[12*testBlockSize : 13*testBlockSize]
		clear(leaf)
	}
	writeDirent(leaf, 0, 3, testBlockSize, "hello.txt", 1)
	return img
}

func TestIndexedDirectoryTraversalAndValidation(t *testing.T) {
	for _, depth := range []byte{0, 1} {
		t.Run(fmt.Sprint(depth), func(t *testing.T) {
			f, err := New(indexedImage(depth))
			if err != nil {
				t.Fatal(err)
			}
			entries, err := f.Root().Children()
			if err != nil {
				t.Fatal(err)
			}
			if len(entries) != 1 || entries[0].Path() != "/hello.txt" {
				t.Fatalf("children: %v", entries)
			}
			if _, err := f.Open("hello.txt"); err != nil {
				t.Fatal(err)
			}
		})
	}
	for _, tc := range []struct {
		name   string
		mutate func([]byte)
	}{
		{"count overflow", func(root []byte) { put16(root, 34, 65535) }},
		{"limit overflow", func(root []byte) { put16(root, 32, 65535) }},
		{"cycle", func(root []byte) { put32(root, 36, 0) }},
		{"out of bounds", func(root []byte) { put32(root, 36, 99) }},
		{"invalid info", func(root []byte) { root[29] = 0 }},
		{"invalid dot", func(root []byte) { root[8] = 'x' }},
		{"unreferenced leaf", func(root []byte) { root[30] = 0 }},
	} {
		t.Run(tc.name, func(t *testing.T) {
			img := indexedImage(1)
			tc.mutate(img.data[10*testBlockSize : 11*testBlockSize])
			f, err := New(img)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := f.Root().Children(); err == nil {
				t.Fatal("accepted malformed HTree")
			}
		})
	}
}

// This fixture is generated by the kernel-format tools, not our test encoder.
// e2fsck -D builds genuine HTree indexes and refreshes metadata checksums.
func TestIndexedDirectoryE2fsprogs(t *testing.T) {
	for _, name := range []string{"mke2fs", "debugfs", "e2fsck"} {
		if _, err := exec.LookPath(name); err != nil {
			t.Skipf("%s unavailable", name)
		}
	}
	for _, blockSize := range []int{1024, 4096} {
		t.Run(fmt.Sprint(blockSize), func(t *testing.T) {
			dir := t.TempDir()
			imgPath := filepath.Join(dir, "indexed.img")
			file, err := os.Create(imgPath)
			if err != nil {
				t.Fatal(err)
			}
			if err := file.Truncate(32 << 20); err != nil {
				t.Fatal(err)
			}
			file.Close()
			run := func(name string, args ...string) {
				t.Helper()
				if out, err := exec.Command(name, args...).CombinedOutput(); err != nil {
					t.Fatalf("%s: %v: %s", name, err, out)
				}
			}
			run("mke2fs", "-q", "-t", "ext4", "-b", fmt.Sprint(blockSize), "-O", "extent,dir_index,metadata_csum,^orphan_file", "-F", imgPath)
			source := filepath.Join(dir, "source")
			if err := os.WriteFile(source, []byte("x"), 0600); err != nil {
				t.Fatal(err)
			}
			var commands strings.Builder
			commands.WriteString("mkdir /indexed\n")
			const files = 700
			for i := 0; i < files; i++ {
				fmt.Fprintf(&commands, "write %s /indexed/file-%04d-long-name.txt\n", source, i)
			}
			script := filepath.Join(dir, "debugfs.commands")
			if err := os.WriteFile(script, []byte(commands.String()), 0600); err != nil {
				t.Fatal(err)
			}
			run("debugfs", "-w", "-f", script, imgPath)
			out, err := exec.Command("e2fsck", "-fyD", imgPath).CombinedOutput()
			if err != nil {
				if exit, ok := err.(*exec.ExitError); !ok || exit.ExitCode() != 1 {
					t.Fatalf("e2fsck: %v: %s", err, out)
				}
			}
			data, err := os.ReadFile(imgPath)
			if err != nil {
				t.Fatal(err)
			}
			f, err := New(&testImage{data: data})
			if err != nil {
				t.Fatal(err)
			}
			entry, err := f.Open("/indexed")
			if err != nil {
				t.Fatal(err)
			}
			concrete := entry.(*Entry)
			inode, err := concrete.fs.readInode(concrete.inode)
			if err != nil {
				t.Fatal(err)
			}
			if inode.flags&inodeFlagIndex == 0 {
				t.Fatal("fixture is not indexed")
			}
			entries, err := entry.Children()
			if err != nil {
				t.Fatal(err)
			}
			if len(entries) != files {
				t.Fatalf("got %d files, want %d", len(entries), files)
			}
			for i, entry := range entries {
				if entry.Path() != fmt.Sprintf("/indexed/file-%04d-long-name.txt", i) {
					t.Fatalf("entry %d: %s", i, entry.Path())
				}
			}
		})
	}
}

func TestIndexedDirectoryRejectsMalformedIndexNodeAndLeaf(t *testing.T) {
	for _, tc := range []struct {
		name   string
		mutate func(*testImage)
	}{
		{"bad index header", func(img *testImage) { put32(img.data[11*testBlockSize:], 0, 3) }},
		{"bad index count", func(img *testImage) { put16(img.data[11*testBlockSize:], 10, 65535) }},
		{"index cycle", func(img *testImage) { put32(img.data[11*testBlockSize:], 12, 1) }},
		{"duplicate index target", func(img *testImage) {
			node := img.data[11*testBlockSize:]
			put16(node, 10, 2)
			put32(node, 16, 100)
			put32(node, 20, 2)
		}},
		{"truncated leaf record", func(img *testImage) { put16(img.data[12*testBlockSize:], 4, 7) }},
	} {
		t.Run(tc.name, func(t *testing.T) {
			img := indexedImage(1)
			tc.mutate(img)
			f, err := New(img)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := f.Root().Children(); err == nil {
				t.Fatal("accepted malformed HTree block")
			}
		})
	}
}

func TestDirectoryRecordLength64KiB(t *testing.T) {
	for _, tc := range []struct {
		raw       uint16
		blockSize uint32
		want      int
	}{
		{0, 65536, 65536}, {65535, 65536, 65536}, {65524, 65536, 65524},
		{12, 65536, 12}, {65535, 4096, 65535}, {0, 4096, 0},
	} {
		if got := directoryRecordLength(tc.raw, tc.blockSize); got != tc.want {
			t.Fatalf("raw %d block size %d: got %d want %d", tc.raw, tc.blockSize, got, tc.want)
		}
	}
}
